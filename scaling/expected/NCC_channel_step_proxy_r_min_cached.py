def load_pickle(path: Path):
    # Static/evolution caches may be generated by NumPy 2.x, whose pickles refer
    # to numpy._core.  Older NumPy builds expose the same modules under
    # numpy.core; install aliases before unpickling so mini can read them.
    sys.modules.setdefault("numpy._core", np.core)
    sys.modules.setdefault("numpy._core.multiarray", np.core.multiarray)
    sys.modules.setdefault("numpy._core.numeric", np.core.numeric)
    sys.modules.setdefault("numpy._core.umath", np.core.umath)
    original_frombuffer = np.core.numeric._frombuffer

    def compat_frombuffer(buf, dtype, shape, order, *args):
        if order == "K":
            order = "C"
        return original_frombuffer(buf, dtype, shape, order)

    np.core.numeric._frombuffer = compat_frombuffer
    sys.modules["numpy._core.numeric"]._frombuffer = compat_frombuffer
    opener = gzip.open if path.suffix == ".gz" else open
    with opener(path, "rb") as handle:
        return pickle.load(handle)


