def output_path(args, q0: int, s0: int, norm: str) -> Path:
    output_dir = resolve_output_dir(args.out_dir, args.tag)
    suffix = normalized_tag_suffix(args.tag)
    mode_label = "log" if args.mode == "log" else "original"
    stem = (
        f"NCC_channel_{mode_label}_step_proxy_r_min_{norm}_N{args.N}_T{args.T:g}"
        f"_eps{args.epsilon:g}"
    )
    if args.mode == "log":
        stem += f"_q{q0}_s{s0}"
    return output_dir / f"{stem}{suffix}"


