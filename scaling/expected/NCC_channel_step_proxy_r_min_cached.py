def frobenius_norm_batch(matrices: np.ndarray) -> np.ndarray:
    matrices = np.asarray(matrices, dtype=complex)
    if matrices.ndim == 2:
        return np.array([np.linalg.norm(matrices, ord="fro")], dtype=float)
    if matrices.ndim != 3:
        raise ValueError(f"expected matrix batch with ndim 2 or 3, got shape={matrices.shape}")
    return np.linalg.norm(matrices.reshape(matrices.shape[0], -1), axis=1).astype(float, copy=False)


def trace_norm_batch(matrices: np.ndarray) -> np.ndarray:
    matrices = np.asarray(matrices, dtype=complex)
    if matrices.ndim == 2:
        return np.array([ncc_channel_log.trace_norm(matrices)], dtype=float)
    if matrices.ndim != 3:
        raise ValueError(f"expected matrix batch with ndim 2 or 3, got shape={matrices.shape}")
    if matrices.shape[-1] == matrices.shape[-2] and np.allclose(
        matrices,
        np.swapaxes(matrices.conj(), -1, -2),
        rtol=1e-10,
        atol=1e-12,
    ):
        hermitian = 0.5 * (matrices + np.swapaxes(matrices.conj(), -1, -2))
        return np.sum(np.abs(np.linalg.eigvalsh(hermitian)), axis=-1).astype(float, copy=False)
    return np.sum(np.linalg.svd(matrices, compute_uv=False), axis=-1).astype(float, copy=False)


def max_batch_error(states_a: np.ndarray, states_b: np.ndarray, norm: str) -> tuple[float, int]:
    diffs = np.asarray(states_a - states_b, dtype=complex)
    if norm == "trace":
        errors = trace_norm_batch(diffs)
        worst_index = int(np.argmax(errors))
        return float(errors[worst_index]), worst_index
    if norm == "frobenius":
        errors = frobenius_norm_batch(diffs)
        worst_index = int(np.argmax(errors))
        return float(errors[worst_index]), worst_index
    raise ValueError(f"unsupported norm={norm!r}")


def ensure_step_batches(mode_impl, static: dict, evolution_data: dict, r: int):
    missing = sorted(STEP_BATCH_FIELDS - set(evolution_data))
    if missing:
        key = (int(static["n"]), float(evolution_data.get("t", np.nan)) * int(r), int(r))
        print(
            f"[cache] building one-step batches r={int(r)} key={key} missing={','.join(missing)}",
            flush=True,
        )
    if "basis_states" not in evolution_data:
        basis_states, basis_labels = mode_impl.computational_basis_density_matrices(static["n"])
        evolution_data["basis_states"] = basis_states
        evolution_data["basis_labels"] = np.array(basis_labels)
    if "step_exact_output_batch" not in evolution_data:
        evolution_data["step_exact_output_batch"] = mode_impl.apply_signed_unitary_channel_to_basis_states(
            evolution_data["step_exact"],
        )
    if "step_expected_output_batch" not in evolution_data:
        step_before = mode_impl.apply_unitary_channel(
            evolution_data["S1"],
            evolution_data["basis_states"],
        )
        evolution_data["step_expected_output_batch"] = evolution_data["apply_tilde_V_expectation"](step_before)
    return evolution_data["step_exact_output_batch"], evolution_data["step_expected_output_batch"]


def search_step_proxy_r_min(
    static: dict,
    t_total: float,
    epsilon: float,
    r_max: int,
    norm: str,
    searches: list[dict],
    checkpoint_cb=None,
    mode_impl=None,
    validation_tol: float = 1e-8,
) -> tuple[int, dict]:
    result_cache: dict[int, dict] = {}
    for item in searches:
        try:
            r = int(item["r"])
        except (KeyError, TypeError, ValueError):
            continue
        if "total_proxy_error" in item and "step_error" in item:
            result_cache[r] = item

    def evaluate_at_r(r: int) -> dict:
        if r in result_cache:
            result = result_cache[r]
            print(
                f"[step-proxy] resume r={r}: step={result['step_error']:.6e}, "
                f"r*step={result['total_proxy_error']:.6e}, threshold={epsilon:.6e}",
                flush=True,
            )
            return result_cache[r]
        cache_key = (int(static["n"]), float(t_total), int(r))
        step_key = normalize_step_key(static["n"], float(t_total) / int(r))
        if cache_key not in EVOLUTION_CACHE:
            if step_key in EVOLUTION_STEP_CACHE:
                source_key, source = EVOLUTION_STEP_CACHE[step_key]
                EVOLUTION_CACHE[cache_key] = align_evolution_data_to_case(
                    mode_impl,
                    static,
                    source,
                    t_total=t_total,
                    r=r,
                    source_key=source_key,
                )
                print(
                    f"[cache] step-size alias r={int(r)} key={cache_key} "
                    f"from source_key={source_key} with step t={source.get('t', float(t_total) / int(r))}",
                    flush=True,
                )
            else:
                print(f"[cache] building tilde_V r={int(r)} key={cache_key}", flush=True)
                if mode_impl is ncc_channel_original:
                    EVOLUTION_CACHE[cache_key] = build_original_evolution_data_fast(static, t_total, r)
                else:
                    EVOLUTION_CACHE[cache_key] = mode_impl.build_tilde_V(static, t_total, r, validation_tol=validation_tol)
        evolution_data = EVOLUTION_CACHE[cache_key]
        evolution_data = hydrate_evolution_data(mode_impl, static, evolution_data)
        exact_step, expected_step = ensure_step_batches(mode_impl, static, evolution_data, r)
        step_error, worst_index = max_batch_error(expected_step, exact_step, norm)
        total_proxy_error = float(r) * step_error
        raw_l1_norm_total = float(evolution_data["raw_l1_norm_total"])
        log_accumulated_l1_norm = float(int(r) * np.log(raw_l1_norm_total))
        accumulated_l1_norm = float(np.exp(log_accumulated_l1_norm)) if log_accumulated_l1_norm < 709 else float("inf")
        result = {
            "r": int(r),
            "step_error": float(step_error),
            "total_proxy_error": float(total_proxy_error),
            "worst_index": int(worst_index),
            "norm": norm,
            "eta_pair_sum": float(evolution_data["eta_pair_sum"]),
            "pair_scale": float(evolution_data["pair_scale"]),
            "raw_l1_norm_total": raw_l1_norm_total,
            "accumulated_l1_norm": accumulated_l1_norm,
            "log_accumulated_l1_norm": log_accumulated_l1_norm,
        }
        result_cache[r] = result
        searches.append(result)
        print(
            f"[step-proxy] eval r={r}: step={step_error:.6e}, "
            f"r*step={total_proxy_error:.6e}, threshold={epsilon:.6e}",
            flush=True,
        )
        if checkpoint_cb is not None:
            checkpoint_cb()
        return result

    low = 0
    high = 1
    high_eval = evaluate_at_r(high)
    while high_eval["total_proxy_error"] > epsilon and high < r_max:
        low = high
        high *= 2
        high_eval = evaluate_at_r(high)
    if high_eval["total_proxy_error"] > epsilon:
        raise RuntimeError(f"failed to reach epsilon={epsilon} by r={r_max} for one-step {norm} proxy")

    while low + 1 < high:
        mid = (low + high) // 2
        mid_eval = evaluate_at_r(mid)
        if mid_eval["total_proxy_error"] <= epsilon:
            high = mid
            high_eval = mid_eval
        else:
            low = mid
    return high, high_eval


def run_case(args, norm: str, case_index: int, total_cases: int, validation_tol: float) -> Path:
    try:
        mode_impl = MODE_IMPLS[args.mode]
    except KeyError as exc:
        raise ValueError(f"unsupported mode={args.mode!r}; expected one of {sorted(MODE_IMPLS)}") from exc

    s0 = int(np.ceil(np.log(4 / args.epsilon))) if args.s0 <= 0 else args.s0
    s0 = max(3, s0)
    q0 = int(np.ceil(np.log(2 * args.N / args.epsilon))) if args.q0 <= 0 else args.q0
    q0 = max(3, q0)

    output_base = output_path(args, q0, s0, norm)
    if args.mode == "log":
        static = mode_impl.build_static_data(n=args.N, q0=q0, s0=s0, j=args.J, h=args.h, K=1)
    else:
        static = mode_impl.build_static_data(n=args.N, j=args.J, h=args.h)
    json_path = Path(f"{output_base}.json")
    payload = {
        "script": "NCC_channel_step_proxy_r_min_cached.py",
        "mode": args.mode,
        "norm": norm,
        "criterion": "r * max_z ||E_step(T/r)(|z><z|) - U_step(T/r)(|z><z|)||",
        "params": {
            "N": args.N,
            "J": args.J,
            "h": args.h,
            "T": args.T,
            "epsilon": args.epsilon,
            "r_max": args.r_max,
            "s0": s0 if args.mode == "log" else None,
            "q0": q0 if args.mode == "log" else None,
        },
        "step_proxy_r_min": None,
        "step_error_at_min": None,
        "total_proxy_error_at_min": None,
        "searches": [],
    }
    if json_path.exists():
        try:
            previous_payload = json.loads(json_path.read_text())
        except json.JSONDecodeError:
            previous_payload = None
        if isinstance(previous_payload, dict):
            if previous_payload.get("step_proxy_r_min") is not None:
                print(
                    f"[case {case_index}/{total_cases}] complete checkpoint exists; skipping: {json_path}",
                    flush=True,
                )
                return output_base
            previous_searches = previous_payload.get("searches", [])
            if isinstance(previous_searches, list) and previous_searches:
                payload["searches"] = previous_searches
                print(
                    f"[case {case_index}/{total_cases}] resuming {len(previous_searches)} prior r evaluations from: {json_path}",
                    flush=True,
                )

    def checkpoint():
        if payload["step_proxy_r_min"] is not None:
            save_checkpoint(output_base, payload)
        else:
            Path(f"{output_base}.json").write_text(json.dumps(payload, indent=2, ensure_ascii=False))

    print(f"[case {case_index}/{total_cases}] one-step {norm} proxy search start", flush=True)
    r_min, metrics = search_step_proxy_r_min(
        static=static,
        t_total=args.T,
        epsilon=args.epsilon,
        r_max=args.r_max,
        norm=norm,
        searches=payload["searches"],
        checkpoint_cb=checkpoint if args.save_every_search else None,
        mode_impl=mode_impl,
        validation_tol=validation_tol,
    )
    payload["step_proxy_r_min"] = int(r_min)
    payload["step_error_at_min"] = float(metrics["step_error"])
    payload["total_proxy_error_at_min"] = float(metrics["total_proxy_error"])
    payload["worst_index_at_min"] = int(metrics["worst_index"])
    payload["raw_l1_norm_total_at_min"] = float(metrics["raw_l1_norm_total"])
    payload["accumulated_l1_norm_at_min"] = float(metrics["accumulated_l1_norm"])
    payload["log_accumulated_l1_norm_at_min"] = float(metrics["log_accumulated_l1_norm"])
    save_checkpoint(output_base, payload)
    print(
        f"[case {case_index}/{total_cases}] step_proxy_r_min={r_min}, "
        f"r*step={metrics['total_proxy_error']:.6e}",
        flush=True,
    )
    print(f"[case {case_index}/{total_cases}] saved checkpoint to: {output_base}.json", flush=True)
    return output_base


def build_parser() -> argparse.ArgumentParser:
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--batch-file", type=Path, required=True)
    parser.add_argument("--norm", choices=("trace", "frobenius"), default="trace")
    parser.add_argument("--static-cache", type=Path, default=None)
    parser.add_argument("--slim-evolution-cache", type=Path, default=None)
    parser.add_argument(
        "--full-evolution-cache",
        type=Path,
        action="append",
        default=None,
        help="Optional full evolution cache layer. May be passed multiple times.",
    )
    parser.add_argument("--require-static-cache", action=argparse.BooleanOptionalAction, default=True)
    parser.add_argument("--require-evolution-cache", action=argparse.BooleanOptionalAction, default=False)
    parser.add_argument(
        "--validation-tol",
        type=float,
        default=1e-8,
        help="Tolerance for tilde_V expectation-vs-Taylor validation when building uncached points.",
    )
    return parser


def main(argv=None) -> int:
    args = build_parser().parse_args(argv)

    cases = load_batch_cases(args.batch_file)
    modes = {case["mode"] for case in cases}
    if len(modes) != 1:
        raise ValueError(f"batch file must contain exactly one mode, got {sorted(modes)}")
    mode = next(iter(modes))
    try:
        mode_impl = MODE_IMPLS[mode]
    except KeyError as exc:
        raise ValueError(f"unsupported mode={mode!r}; expected one of {sorted(MODE_IMPLS)}") from exc

    if args.static_cache is None:
        args.static_cache = DEFAULT_STATIC_CACHE if mode == "log" else DEFAULT_ORIGINAL_STATIC_CACHE
    if args.slim_evolution_cache is None:
        args.slim_evolution_cache = DEFAULT_SLIM_CACHE if mode == "log" else DEFAULT_ORIGINAL_SLIM_CACHE

    static_cache = install_static_cache(mode, mode_impl, args.static_cache, args.require_static_cache)
    install_evolution_cache(mode_impl, args.slim_evolution_cache, static_cache, args.require_evolution_cache)
    full_evolution_caches = args.full_evolution_cache
    if full_evolution_caches is None:
        full_evolution_caches = DEFAULT_FULL_CACHES if mode == "log" else DEFAULT_ORIGINAL_FULL_CACHES
    for path in full_evolution_caches:
        install_evolution_cache(mode_impl, path, static_cache, args.require_evolution_cache)
    print(f"[cache] final EVOLUTION_CACHE entries: {len(EVOLUTION_CACHE)}", flush=True)

    print(f"loaded {len(cases)} cases from {args.batch_file}", flush=True)
    for idx, case in enumerate(cases, start=1):
        run_case(
            case_namespace(case),
            norm=args.norm,
            case_index=idx,
            total_cases=len(cases),
            validation_tol=args.validation_tol,
        )
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
